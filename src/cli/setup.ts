// `jarvis-meeting setup` — scaffold a teammate SOUL.md (and an .env.local
// template if missing). The SOUL front-matter shape + defaults are taken from
// the zod schema (SoulFrontMatter) so this never re-states field names/defaults
// that the schema already owns: we feed the flag-derived overrides THROUGH the
// schema and serialize the validated result.

import { existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import * as yaml from 'js-yaml';
import { SoulFrontMatter, type PersonaMode } from '../soul/schema.js';
import { soulPath } from '../soul/loader.js';

export interface SetupOptions {
  teammate: string;
  name?: string;
  persona?: PersonaMode;
  endpoint?: string;
  soulDir: string;
  /** Project root where the .env.local template is written if absent. */
  projectDir: string;
  force: boolean;
}

export interface SetupResult {
  soulFile: string;
  soulWritten: boolean;
  envFile: string;
  envWritten: boolean;
  nextSteps: string[];
}

/**
 * Build the validated SOUL front-matter object from flags. Overrides are run
 * THROUGH SoulFrontMatter.parse so every field name + default originates from
 * the schema (no duplication) and the result is guaranteed valid.
 */
function buildFrontMatter(opts: SetupOptions): Record<string, unknown> {
  const overrides: Record<string, unknown> = {
    owner: opts.teammate,
    name: opts.name ?? opts.teammate,
  };
  if (opts.persona !== undefined) overrides['persona_mode'] = opts.persona;
  if (opts.endpoint !== undefined) {
    overrides['knowledge_backend'] = { type: 'folder', endpoint: opts.endpoint };
  }
  // parse() applies the schema defaults to every field we did not set.
  const parsed = SoulFrontMatter.parse(overrides);
  return parsed as unknown as Record<string, unknown>;
}

export const ENV_TEMPLATE = `# jarvis-meeting — local environment template (generated by \`jarvis-meeting setup\`)
# Fill these in, then \`npm run dev\`. Required keys first.

# --- Required ---
RECALL_API_KEY=        # Recall.ai API key
RECALL_API_BASE=       # region base, e.g. https://us-west-2.recall.ai/api/v1 (must match your key's region)
PUBLIC_BASE_URL=       # public HTTPS origin Recall reaches (ngrok locally; \`up\` resolves this)

# Per-teammate dispatch token registry: token1:teammate1,token2:teammate2
JARVIS_TOKENS=
# Shared secret Recall presents on the webhook URL (?s=...). Set before exposing publicly.
WEBHOOK_SECRET=
# Display name AND wake word for YOUR bot — make it UNIQUE (not "Jarvis") so multiple bots don't collide.
JARVIS_BOT_NAME=

# --- Realtime provider (OpenAI; defaults to gpt-realtime-mini) ---
OPENAI_API_KEY=

# --- Knowledge (the 'ai'/team persona route reads this; folder/connector base URL) ---
TEAM_KB_RETRIEVAL_URL=

# --- Post-meeting (optional features) ---
# Summary + transcript ingest (required for both):
ANTHROPIC_API_KEY=
# Send summary + transcript to your own Slack DM:
SLACK_BOT_TOKEN=
MEETING_SLACK_CHANNEL=   # your Slack user ID (onboard resolves it via auth.test)
`;

/** Render the SOUL.md text from validated front-matter + a starter prose body. */
export function renderSoul(frontMatter: Record<string, unknown>, prose: string): string {
  const fm = yaml.dump(frontMatter, { lineWidth: 100 }).trimEnd();
  return `---\n${fm}\n---\n${prose}\n`;
}

/**
 * Scaffold the SOUL file (and .env.local template if missing). Pure w.r.t. the
 * filesystem paths passed in — no process.env, no cwd — so tests drive it with a
 * temp dir. Refuses to overwrite an existing SOUL unless force is set.
 */
export function scaffoldSoul(opts: SetupOptions): SetupResult {
  const soulFile = soulPath(opts.teammate, opts.soulDir);

  if (existsSync(soulFile) && !opts.force) {
    throw new Error(`SOUL already exists at ${soulFile} (use --force to overwrite)`);
  }

  mkdirSync(opts.soulDir, { recursive: true });
  const frontMatter = buildFrontMatter(opts);
  const prose = `You are ${frontMatter['name'] as string}. Answer questions grounded in your knowledge base. Be brief but complete: lead with the answer, add only the context that matters, and stop. If you do not have the information, say so plainly rather than guessing.`;
  writeFileSync(soulFile, renderSoul(frontMatter, prose), 'utf8');

  const envFile = join(opts.projectDir, '.env.local');
  let envWritten = false;
  if (!existsSync(envFile)) {
    writeFileSync(envFile, ENV_TEMPLATE, 'utf8');
    envWritten = true;
  }

  const nextSteps = [
    `1. Edit ${soulFile} — set the voice, denied topics, delivery, and prose.`,
    ...(envWritten
      ? [`2. Fill in ${envFile} (RECALL_API_KEY, PUBLIC_BASE_URL, a realtime provider).`]
      : [`2. ${envFile} already exists — leaving it untouched.`]),
    `3. Run \`jarvis-meeting doctor --teammate ${opts.teammate}\` to verify.`,
    `4. \`npm run dev\` then POST /v1/dispatch with this teammate's token.`,
  ];

  return { soulFile, soulWritten: true, envFile, envWritten, nextSteps };
}
